/**
 * Returns localized Telugu planet name if lang === 'te'
 */
export function getLocalizedPlanet(name, lang = 'te') {
    if (!name) return '';
    if (lang !== 'te') return name;

    // Handle names with node mode suffixes like "Rahu (Mean Node)" or "Rahu (True Node)"
    if (typeof name === 'string' && name.includes('(')) {
        const base = name.split('(')[0].trim();
        return TELUGU_PLANET_NAMES[base] || TELUGU_PLANET_NAMES[name] || name;
    }

    return TELUGU_PLANET_NAMES[name] || name;
}

/**
 * Returns localized Telugu nakshatra name if lang === 'te'
 */
export function getLocalizedNakshatra(nak, lang = 'te') {
    if (!nak) return '';
    if (lang !== 'te') return typeof nak === 'object' ? (nak.name || '') : nak;
    if (typeof nak === 'object') {
        return nak.te || NAKSHATRA_TELUGU_NAMES[nak.name] || nak.name || '';
    }
    return NAKSHATRA_TELUGU_NAMES[nak] || nak;
}

